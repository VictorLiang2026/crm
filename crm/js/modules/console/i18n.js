/** Translate a database enum value through the centralized registry.
 *  Falls back to the raw value; logs a warning in dev mode for missing mappings. */
export function translateEnum(type, value) {
  if (!value) return value;
  const map = ENUM_I18N[type];
  if (!map) return value;
  const key = map[value];
  if (!key) {
    if (typeof window !== 'undefined' && window.__DEV__) {
      console.warn(`[i18n] Missing enum mapping: type="${type}", value="${value}"`);
    }
    return value;
  }
  return t(key);
}

export function getLang() {
  if (_lang) return _lang;
  try { _lang = localStorage.getItem('crm_lang') || DEFAULT; } catch (_) {}
  _lang = _lang || DEFAULT;
  return _lang;
}

export function setLang(lang) {
  _lang = lang || DEFAULT;
  try { localStorage.setItem('crm_lang', _lang); } catch (_) {}
  document.querySelectorAll('[data-i18n]').forEach(n => {
    const k = n.getAttribute('data-i18n');
    if (k) n.textContent = t(k);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(n => {
    const k = n.getAttribute('data-i18n-aria');
    if (k) n.setAttribute('aria-label', t(k));
  });
}

export function t(key) {
  const d = DICT[key];
  if (!d) return key;
  return d[getLang()] || d[DEFAULT] || key;
}

export function tFull(key) {
  const d = DICT[key];
  if (!d) return key;
  return d['en_full'] || d[getLang()] || d[DEFAULT] || key;
}

/** Replace i18n placeholders in a node tree. Call after render. */
export function scanI18n(root) {
  root?.querySelectorAll?.('[data-i18n]')?.forEach?.(n => {
    const k = n.getAttribute('data-i18n');
    if (k) n.textContent = t(k);
  });
  root?.querySelectorAll?.('[data-i18n-aria]')?.forEach?.(n => {
    const k = n.getAttribute('data-i18n-aria');
    if (k) n.setAttribute('aria-label', t(k));
  });
}
