BEGIN;
SET LOCAL lock_timeout = '5s';

DO $guard$
BEGIN
  IF to_regclass('public.person_followup_advice') IS NOT NULL THEN
    RAISE EXCEPTION 'public.person_followup_advice already exists; inspect before migrating';
  END IF;
END $guard$;

CREATE TABLE public.person_followup_advice (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id bigint NOT NULL REFERENCES public.persons(id) ON DELETE RESTRICT,
  client_request_id uuid NOT NULL,
  title text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 240),
  system_status text NOT NULL DEFAULT 'generating'
    CHECK (system_status IN ('generating','ready','failed')),
  system_strategy text,
  system_product_advice text,
  system_strategy_sources jsonb NOT NULL DEFAULT '[]'::jsonb
    CHECK (jsonb_typeof(system_strategy_sources)='array'),
  system_product_sources jsonb NOT NULL DEFAULT '[]'::jsonb
    CHECK (jsonb_typeof(system_product_sources)='array'),
  system_version integer NOT NULL DEFAULT 0 CHECK (system_version >= 0),
  system_task_id bigint REFERENCES public.ai_tasks(id) ON DELETE RESTRICT,
  gpt_strategy text,
  gpt_product_advice text,
  gpt_strategy_sources jsonb NOT NULL DEFAULT '[]'::jsonb
    CHECK (jsonb_typeof(gpt_strategy_sources)='array'),
  gpt_product_sources jsonb NOT NULL DEFAULT '[]'::jsonb
    CHECK (jsonb_typeof(gpt_product_sources)='array'),
  gpt_based_on_system_version integer CHECK (gpt_based_on_system_version IS NULL OR gpt_based_on_system_version > 0),
  gpt_kept_for_system_version integer CHECK (gpt_kept_for_system_version IS NULL OR gpt_kept_for_system_version > 0),
  gpt_status text NOT NULL DEFAULT 'pending'
    CHECK (gpt_status IN ('pending','ready','stale','kept','manual')),
  gpt_preview_id uuid,
  gpt_preview_payload jsonb,
  gpt_preview_actor text,
  gpt_preview_expires_at timestamptz,
  created_by text NOT NULL CHECK (length(btrim(created_by)) BETWEEN 1 AND 256),
  updated_by text NOT NULL CHECK (length(btrim(updated_by)) BETWEEN 1 AND 256),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  UNIQUE (person_id, client_request_id),
  CHECK ((system_status='ready' AND system_version > 0 AND system_strategy IS NOT NULL
      AND system_product_advice IS NOT NULL)
    OR (system_status IN ('generating','failed') AND system_version=0)),
  CHECK ((gpt_strategy IS NULL AND gpt_product_advice IS NULL
      AND gpt_based_on_system_version IS NULL)
    OR (gpt_strategy IS NOT NULL AND gpt_product_advice IS NOT NULL
      AND gpt_based_on_system_version IS NOT NULL)),
  CHECK ((gpt_preview_id IS NULL AND gpt_preview_payload IS NULL
      AND gpt_preview_actor IS NULL AND gpt_preview_expires_at IS NULL)
    OR (gpt_preview_id IS NOT NULL AND jsonb_typeof(gpt_preview_payload)='object'
      AND gpt_preview_actor IS NOT NULL AND gpt_preview_expires_at IS NOT NULL))
);

CREATE INDEX person_followup_advice_person_updated_idx
  ON public.person_followup_advice(person_id,updated_at DESC,id DESC)
  WHERE deleted_at IS NULL;
CREATE INDEX person_followup_advice_gpt_queue_idx
  ON public.person_followup_advice(gpt_status,updated_at,id)
  WHERE deleted_at IS NULL AND system_status='ready';

ALTER TABLE public.person_followup_advice ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.person_followup_advice FORCE ROW LEVEL SECURITY;
CREATE POLICY person_followup_advice_service_only ON public.person_followup_advice
  FOR ALL TO service_role USING (true) WITH CHECK (true);
REVOKE ALL ON TABLE public.person_followup_advice FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.person_followup_advice TO service_role;
REVOKE ALL ON SEQUENCE public.person_followup_advice_id_seq FROM PUBLIC, anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.person_followup_advice_id_seq TO service_role;

COMMENT ON TABLE public.person_followup_advice IS
  'Paired parallel CloudBase and ChatGPT follow-up advice for one Person; GPT payload writes require a version-checked human preview confirmation.';

COMMIT;
