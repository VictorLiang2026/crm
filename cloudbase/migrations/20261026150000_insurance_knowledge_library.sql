CREATE FUNCTION public.crm_ai_finish_dual_v1(
  p_task_id bigint, p_run_id bigint, p_success boolean, p_error text,
  p_usage jsonb, p_candidates jsonb, p_final boolean
) RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public AS $fn$
DECLARE
  v_task public.ai_tasks%ROWTYPE;
  v_run public.ai_runs%ROWTYPE;
  v_result_ids bigint[];
  v_item jsonb;
  v_kind text;
  v_rank integer;
  v_count integer;
  v_types integer;
BEGIN
  IF current_user <> 'service_role' THEN RAISE EXCEPTION 'AI audit service role required'; END IF;
  IF p_task_id IS NULL OR p_task_id <= 0 OR p_success IS NULL OR p_final IS NULL
     OR jsonb_typeof(p_usage) IS DISTINCT FROM 'object'
     OR (p_success AND (p_run_id IS NULL OR jsonb_typeof(p_candidates) IS DISTINCT FROM 'array'))
     OR (NOT p_success AND (p_error IS NULL OR length(p_error) NOT BETWEEN 1 AND 100))
     OR (p_run_id IS NULL AND (p_success OR NOT p_final)) THEN
    RAISE EXCEPTION 'Invalid dual AI finalization input';
  END IF;
  SELECT * INTO v_task FROM public.ai_tasks WHERE id=p_task_id FOR UPDATE;
  IF NOT FOUND OR v_task.skill_name <> 'dual_followup' OR v_task.task_type <> 'customer_followup_dual' THEN
    RAISE EXCEPTION 'Dual AI task not found';
  END IF;
  IF p_run_id IS NULL THEN
    IF v_task.status='running' THEN
      UPDATE public.ai_tasks SET status='failed',completed_at=now() WHERE id=p_task_id;
    ELSIF v_task.status <> 'failed' THEN
      RAISE EXCEPTION 'AI task already finalized differently';
    END IF;
    RETURN jsonb_build_object('status','failed','taskId',p_task_id);
  END IF;
  SELECT * INTO v_run FROM public.ai_runs WHERE id=p_run_id AND task_id=p_task_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'AI run not found for task'; END IF;
  IF v_run.success IS NOT NULL THEN
    IF v_run.success IS DISTINCT FROM p_success THEN RAISE EXCEPTION 'AI run replay changed outcome'; END IF;
    IF p_success THEN
      SELECT array_agg(id ORDER BY rank,id) INTO v_result_ids FROM public.ai_results
        WHERE task_id=p_task_id AND run_id=p_run_id;
      IF coalesce(cardinality(v_result_ids),0) <> 2 THEN RAISE EXCEPTION 'Dual AI run must have two results'; END IF;
      RETURN jsonb_build_object('status','completed','taskId',p_task_id,
        'runId',p_run_id,'resultIds',to_jsonb(v_result_ids));
    END IF;
    RETURN jsonb_build_object('status',CASE WHEN v_task.status='failed' THEN 'failed' ELSE 'retry' END,
      'taskId',p_task_id,'runId',p_run_id);
  END IF;
  IF v_task.status <> 'running' THEN RAISE EXCEPTION 'AI task is not running'; END IF;
  UPDATE public.ai_runs SET success=p_success,
    error=CASE WHEN p_success THEN NULL ELSE p_error END,
    provider=p_usage->>'provider',model=p_usage->>'model',
    input_tokens=NULLIF(p_usage->>'input_tokens','')::bigint,
    output_tokens=NULLIF(p_usage->>'output_tokens','')::bigint,
    cached_tokens=NULLIF(p_usage->>'cached_tokens','')::bigint,
    cost=NULLIF(p_usage->>'cost','')::numeric,
    latency_ms=NULLIF(p_usage->>'latency_ms','')::bigint
    WHERE id=p_run_id;
  IF p_success THEN
    SELECT count(*), count(DISTINCT value->>'candidateType')
      INTO v_count,v_types FROM jsonb_array_elements(p_candidates);
    IF v_count <> 2 OR v_types <> 2 OR EXISTS (
      SELECT 1 FROM jsonb_array_elements(p_candidates) c(value)
      WHERE jsonb_typeof(value) IS DISTINCT FROM 'object'
        OR value->>'candidateType' NOT IN ('strategy_based','library_based')
    ) OR NOT EXISTS (SELECT 1 FROM jsonb_array_elements(p_candidates) c(value) WHERE value->>'candidateType'='strategy_based')
      OR NOT EXISTS (SELECT 1 FROM jsonb_array_elements(p_candidates) c(value) WHERE value->>'candidateType'='library_based') THEN
      RAISE EXCEPTION 'Dual AI candidates must include exactly strategy_based and library_based';
    END IF;
    FOR v_item IN SELECT value FROM jsonb_array_elements(p_candidates) LOOP
      v_kind := v_item->>'candidateType';
      v_rank := CASE v_kind WHEN 'strategy_based' THEN 1 ELSE 2 END;
      INSERT INTO public.ai_results(task_id,run_id,result_json,rank,is_recommended,user_selected,user_edited)
      VALUES (p_task_id,p_run_id,v_item,v_rank,false,false,false);
    END LOOP;
    SELECT array_agg(id ORDER BY rank,id) INTO v_result_ids FROM public.ai_results
      WHERE task_id=p_task_id AND run_id=p_run_id;
    UPDATE public.ai_tasks SET status='completed',completed_at=now() WHERE id=p_task_id;
    RETURN jsonb_build_object('status','completed','taskId',p_task_id,
      'runId',p_run_id,'resultIds',to_jsonb(v_result_ids));
  END IF;
  IF p_final THEN UPDATE public.ai_tasks SET status='failed',completed_at=now() WHERE id=p_task_id; END IF;
  RETURN jsonb_build_object('status',CASE WHEN p_final THEN 'failed' ELSE 'retry' END,
    'taskId',p_task_id,'runId',p_run_id);
END $fn$;

CREATE FUNCTION public.crm_ai_select_dual_v1(
  p_task_id bigint, p_result_id bigint, p_actor_uid text, p_final_result jsonb
) RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public AS $fn$
DECLARE
  v_task public.ai_tasks%ROWTYPE;
  v_result public.ai_results%ROWTYPE;
BEGIN
  IF current_user <> 'service_role' THEN RAISE EXCEPTION 'AI audit service role required'; END IF;
  IF p_task_id IS NULL OR p_result_id IS NULL OR p_actor_uid IS NULL
     OR length(btrim(p_actor_uid)) NOT BETWEEN 1 AND 256
     OR jsonb_typeof(p_final_result) IS DISTINCT FROM 'object' THEN
    RAISE EXCEPTION 'Invalid dual AI selection input';
  END IF;
  SELECT * INTO v_task FROM public.ai_tasks WHERE id=p_task_id FOR UPDATE;
  IF NOT FOUND OR v_task.skill_name <> 'dual_followup' OR v_task.status <> 'completed' THEN
    RAISE EXCEPTION 'Dual AI task is unavailable';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.ai_request_claims c
    WHERE c.task_id=p_task_id AND c.actor_uid=p_actor_uid) THEN
    RAISE EXCEPTION 'Dual AI actor does not own task';
  END IF;
  SELECT * INTO v_result FROM public.ai_results
    WHERE id=p_result_id AND task_id=p_task_id
      AND result_json->>'candidateType' IN ('strategy_based','library_based')
    FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Dual AI candidate not found'; END IF;
  UPDATE public.ai_results SET user_selected=false,user_edited=false,final_result_json=NULL
    WHERE task_id=p_task_id AND id<>p_result_id;
  UPDATE public.ai_results SET user_selected=true,
    user_edited=(result_json IS DISTINCT FROM p_final_result),
    final_result_json=p_final_result
    WHERE id=p_result_id;
  RETURN jsonb_build_object('status','selected','taskId',p_task_id,'resultId',p_result_id,
    'candidateType',v_result.result_json->>'candidateType',
    'userEdited',(v_result.result_json IS DISTINCT FROM p_final_result));
END $fn$;

REVOKE ALL ON FUNCTION public.crm_ai_finish_dual_v1(bigint,bigint,boolean,text,jsonb,jsonb,boolean)
  FROM PUBLIC,anon,authenticated;
REVOKE ALL ON FUNCTION public.crm_ai_select_dual_v1(bigint,bigint,text,jsonb)
  FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.crm_ai_finish_dual_v1(bigint,bigint,boolean,text,jsonb,jsonb,boolean)
  TO service_role;
GRANT EXECUTE ON FUNCTION public.crm_ai_select_dual_v1(bigint,bigint,text,jsonb)
  TO service_role;

COMMIT;
