BEGIN
  IF to_regclass('public.knowledge_sources') IS NOT NULL
     OR EXISTS (
       SELECT 1 FROM information_schema.columns
       WHERE table_schema='public' AND table_name='knowledge_items' AND column_name='source_id'
     )
     OR to_regprocedure('public.crm_ai_finish_dual_v1(bigint,bigint,boolean,text,jsonb,jsonb,boolean)') IS NOT NULL
     OR to_regprocedure('public.crm_ai_select_dual_v1(bigint,bigint,text,jsonb)') IS NOT NULL THEN
    RAISE EXCEPTION 'Knowledge library objects already exist; inspect before migrating';
  END IF;
END $guard$;

CREATE TABLE public.knowledge_sources (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  domain text NOT NULL CHECK (domain IN (
    'product','company','service','recruitment','industry','campaign',
    'health_wealth_seminar','top_performer_sharing','legal_tax','case','playbook'
  )),
  title text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 500),
  publisher text,
  jurisdiction text,
  source_uri text CHECK (source_uri IS NULL OR source_uri ~ '^https://'),
  published_at date,
  valid_from date,
  valid_to date,
  review_at date,
  storage_key text,
  file_name text CHECK (file_name IS NULL OR length(file_name) <= 255),
  content_type text CHECK (content_type IS NULL OR length(content_type) <= 120),
  file_size_bytes integer CHECK (file_size_bytes IS NULL OR file_size_bytes BETWEEN 1 AND 3145728),
  sha256 text CHECK (sha256 IS NULL OR sha256 ~ '^[0-9a-f]{64}$'),
  extraction_status text NOT NULL DEFAULT 'not_started'
    CHECK (extraction_status IN ('not_started','queued','extracting','draft','failed','unsupported')),
  lifecycle_status text NOT NULL DEFAULT 'draft'
    CHECK (lifecycle_status IN ('draft','verified','superseded','invalidated')),
  supersedes_id bigint REFERENCES public.knowledge_sources(id) ON DELETE RESTRICT,
  version_no integer NOT NULL DEFAULT 1 CHECK (version_no > 0),
  extracted_at timestamptz,
  created_by text,
  updated_by text,
  verified_by text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata)='object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (valid_from IS NULL OR valid_to IS NULL OR valid_to >= valid_from),
  CHECK ((storage_key IS NULL) = (file_name IS NULL)),
  CHECK ((storage_key IS NULL) = (sha256 IS NULL)),
  UNIQUE (storage_key),
  UNIQUE (sha256)
);
CREATE INDEX knowledge_sources_domain_status_idx
  ON public.knowledge_sources(domain,lifecycle_status,valid_to,review_at,updated_at DESC);
CREATE INDEX knowledge_sources_supersedes_idx ON public.knowledge_sources(supersedes_id);
