'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {PGlite}=require(process.env.CRM_PGLITE_MODULE||'@electric-sql/pglite');
const {activityRoster}=require('../../cloudfunctions/person_360/activity-roster');
test('employee roster import, identity, history, edits, concurrency and replay',async()=>{
 const db=new PGlite();try{
 await db.exec(`CREATE ROLE anon;CREATE ROLE authenticated;CREATE ROLE service_role BYPASSRLS;
 CREATE TABLE public.activities(id integer primary key,name text,activity_date date,location text,deleted_at timestamptz,actual_participants integer);
 CREATE TABLE public.persons(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,display_name text,name_key text,phone text,wechat text,organization text,occupation text,updated_at timestamptz DEFAULT now(),deleted_at timestamptz);
 CREATE TABLE public.activity_participants(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,activity_id integer,canonical_person_id bigint,person_type text,person_name text,status text,participant_role text,updated_at timestamptz,deleted_at timestamptz);
 GRANT ALL ON public.activities,public.persons,public.activity_participants TO service_role; GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
 INSERT INTO public.activities(id,name) VALUES(1,'Fixture A'),(2,'Fixture B');`);
 await db.exec(fs.readFileSync(path.resolve(__dirname,'../../cloudbase/migrations/20261112085000_activity_roster.sql'),'utf8'));
 await db.exec('SET ROLE service_role');
 const run=(op,data,actor='tester')=>activityRoster(actor,op,data,async(name,p)=>(await db.query('SELECT public.crm_activity_roster_v1($1,$2,$3) r',[p.p_actor,p.p_op,p.p_input])).rows[0].r);
 const values={display_name:'Chen',school:'Test school',phone:'001000'};const first={choice:'independent',values};
 const commit=async(operation,rows,activityId)=>{const p=await run('prepare',{operation,rows,activityId});return run('confirm',{previewId:p.previewId});};
 const a=await run('prepare',{operation:'import',activityId:1,rows:[first]});
 await assert.rejects(run('confirm',{previewId:a.previewId},'other'),/ROSTER_INVALID/);
 const result=await run('confirm',{previewId:a.previewId});assert.equal(result.added,1);assert.deepEqual(await run('confirm',{previewId:a.previewId}),result);
 const p=(await run('list',{activityId:1})).rows[0];assert.equal(p.phone,'001000');assert.equal(p.person_id,null);
 const select={choice:'profile',id:p.id,values};
 assert.equal((await commit('import',[select],1)).added,0);await commit('import',[select],2);
 assert.equal((await run('history',{id:p.id})).total,2);
 await commit('edit',[{...select,version:p.version,values:{...values,school:'Another school'}}]);
 assert.equal((await run('profile',{id:p.id})).school,'Another school');
 await assert.rejects(commit('edit',[{...select,version:p.version}]),/ROSTER_CONFLICT/);
 const v=await run('profile',{id:p.id});const linked=await commit('createPerson',[{...select,version:v.version}]);
 assert.ok(linked.personId);assert.equal((await run('personHistory',{personId:linked.personId})).total,2);
 const updated=await run('profile',{id:p.id});await commit('remove',[{...select,version:updated.version}],2);
 assert.equal((await run('history',{id:p.id})).total,1);assert.equal((await run('list',{activityId:2})).imported,true);
 const names=(await db.query("INSERT INTO public.persons(display_name,name_key,phone) VALUES ('Lin (A)','lin','111'),('Lin (B)','lin','222') RETURNING id")).rows;
 const sameName={display_name:'Lin',phone:'from-file'};
 const possible=await run('analyze',{rows:[{values:sameName}]});
 assert.equal(possible.rows[0].candidates.length,2);
 await assert.rejects(commit('import',[{choice:'person',personId:linked.personId,values:sameName}],2),/ROSTER_CONFLICT/);
 for(const person of names)await commit('import',[{choice:'person',personId:person.id,values:sameName}],2);
 const two=await run('list',{activityId:2});
 assert.deepEqual(two.rows.map(row=>row.phone).sort(),['111','222']);
 assert.equal((await commit('import',[{choice:'person',personId:names[0].id,values:sameName}],2)).added,0);
 assert.equal((await run('personHistory',{personId:names[0].id})).total,1);
 await db.exec('RESET ROLE; SET ROLE anon');
 const acl=(await db.query("select has_table_privilege(current_user,'public.activity_roster_people','SELECT') AS r,has_function_privilege(current_user,'public.crm_activity_roster_v1(text,text,jsonb)','EXECUTE') AS e")).rows[0];assert.deepEqual(acl,{r:false,e:false});
 }finally{await db.close();}
});
