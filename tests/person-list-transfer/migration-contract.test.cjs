'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require(process.env.CRM_PGLITE_MODULE || '@electric-sql/pglite');

const root = path.resolve(__dirname, '../..');
const read = name => fs.readFileSync(path.join(root, 'cloudbase/migrations', name), 'utf8');
const commands = read('20261109160000_person_list_transfer_commands.sql');
const commandsRollback = read('20261109160000_person_list_transfer_commands.rollback.sql');
const atomicCreate = read('20261109170000_person_list_transfer_atomic_create.sql');
const atomicRollback = read('20261109170000_person_list_transfer_atomic_create.rollback.sql');
const rosterLinkMigration = read('20261114154600_person_list_transfer_activity_roster_link.sql');

test('command migration is public-only, service-only and requires the ready confirmation state', () => {
  assert.match(commands, /CREATE TABLE public\.crm_person_list_transfer_commands/);
  assert.match(commands, /ENABLE ROW LEVEL SECURITY[\s\S]*FORCE ROW LEVEL SECURITY/);
  assert.match(commands, /REVOKE ALL ON public\.crm_person_list_transfer_commands FROM PUBLIC, anon, authenticated, service_role/);
  assert.match(commands, /GRANT SELECT, INSERT, UPDATE ON public\.crm_person_list_transfer_commands TO service_role/);
  assert.match(commands, /status IN \('preview','ready','executing','partial','completed','stale','expired'\)/);
  assert.doesNotMatch(commands, /\bpr(?:_[a-z0-9_]+)?\b/i);
});

test('command rollback guards unfinished confirmed executions and does not cascade', () => {
  assert.match(commandsRollback, /status IN \('ready','executing','partial'\)/);
  assert.match(commandsRollback, /DROP TABLE public\.crm_person_list_transfer_commands/);
  assert.doesNotMatch(commandsRollback, /CASCADE/i);
});

test('different-person rename and create share one locked public transaction', () => {
  assert.match(atomicCreate, /CREATE FUNCTION public\.crm_person_list_transfer_create_v1/);
  assert.match(atomicCreate, /current_user <> 'service_role'/);
  assert.match(atomicCreate, /FOR UPDATE/);
  assert.match(atomicCreate, /updated_at IS DISTINCT FROM/);
  assert.match(atomicCreate, /UPDATE public\.persons[\s\S]*?INSERT INTO public\.persons/);
  assert.match(atomicCreate, /GRANT EXECUTE ON FUNCTION public\.crm_person_list_transfer_create_v1\(text,jsonb,jsonb\) TO service_role/);
  assert.doesNotMatch(atomicCreate, /\bpr(?:_[a-z0-9_]+)?\b/i);
  assert.match(atomicRollback, /DROP FUNCTION public\.crm_person_list_transfer_create_v1\(text,jsonb,jsonb\)/);
  assert.doesNotMatch(atomicRollback, /CASCADE/i);
});

test('new qualified or plain Person can link a reviewed roster profile atomically and stale versions fail closed', async () => {
  const db = new PGlite();
  try {
    await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
      CREATE TYPE public."客户经营阶段" AS ENUM ('新认识'); CREATE TYPE public."优先级" AS ENUM ('A');
      CREATE TABLE public.persons(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,display_name text,name_key text,
        phone text,wechat text,gender text,birthday date,occupation text,organization text,education text,source text,hobbies text,
        customer_stage public."客户经营阶段",sales_priority public."优先级",referral_priority public."优先级",marital_status text,
        first_contact_date date,notes text,updated_at timestamptz DEFAULT now(),deleted_at timestamptz);
      CREATE TABLE public.activity_roster_people(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,person_id bigint,
        display_name text,name_key text,phone text,wechat text,organization text,school text,version bigint DEFAULT 1,updated_at timestamptz DEFAULT now());
      CREATE TABLE public.activity_participants(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,roster_id bigint,
        canonical_person_id bigint,person_name text,updated_at timestamptz);
      GRANT ALL ON ALL TABLES IN SCHEMA public TO service_role; GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;`);
    const start = rosterLinkMigration.indexOf('CREATE OR REPLACE FUNCTION public.crm_person_list_transfer_create_v1');
    const end = rosterLinkMigration.indexOf('REVOKE ALL ON FUNCTION public.crm_person_list_transfer_create_v1', start);
    assert.ok(start >= 0 && end > start);
    await db.exec(rosterLinkMigration.slice(start, end));
    await db.exec(`INSERT INTO public.activity_roster_people(id,display_name,name_key,phone,wechat,organization,school,version)
      VALUES(10,'Kai','kai','0099','kai-wx','Event org','Event school',4);
      INSERT INTO public.activity_participants(roster_id,canonical_person_id,person_name) VALUES(10,NULL,'Kai');
      SET ROLE service_role;`);
    const payload = { display_name:'Kai',name_key:'kai',phone:'',wechat:'',organization:'',education:'',
      activityRosterLink:{id:'10',version:'4',displayName:'Kai'} };
    const created = (await db.query('SELECT public.crm_person_list_transfer_create_v1($1,$2,$3) result',
      ['tester',[],payload])).rows[0].result;
    assert.equal(created.ok,true);assert.equal(created.activityRosterLinked,true);
    const person=(await db.query('SELECT display_name,phone,wechat,organization,education FROM public.persons WHERE id=$1',[created.personId])).rows[0];
    assert.deepEqual(person,{display_name:'Kai',phone:'0099',wechat:'kai-wx',organization:'Event org',education:'Event school'});
    assert.equal((await db.query('SELECT canonical_person_id FROM public.activity_participants WHERE roster_id=10')).rows[0].canonical_person_id,created.personId);
    await db.query(`INSERT INTO public.activity_roster_people(id,display_name,name_key,version) VALUES(11,'Mia','mia',5)`);
    await assert.rejects(db.query('SELECT public.crm_person_list_transfer_create_v1($1,$2,$3)',
      ['tester',[],{display_name:'Mia',name_key:'mia',activityRosterLink:{id:'11',version:'4',displayName:'Mia'}}]),/candidate changed/);
    assert.equal((await db.query("SELECT count(*)::int n FROM public.persons WHERE display_name='Mia'")).rows[0].n,0);
  } finally { await db.close(); }
});

