'use strict';
const test=require('node:test'), assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const modulePath=process.env.CRM_PGLITE_MODULE||'@electric-sql/pglite';
const {PGlite}=require(modulePath),{pgcrypto}=require(path.join(path.dirname(require.resolve(modulePath)),'contrib/pgcrypto.cjs'));
const {makeEnvelope,decryptResult}=require('../../cloudfunctions/activity_registration/registration-signed');
test('signed RPCs serve the public and approved staff journeys, retries, recovery and independent revocation',async()=>{
 const db=new PGlite({extensions:{pgcrypto}});
 const sql=(name,end='')=>fs.readFileSync(path.resolve(__dirname,'../../cloudbase/migrations',name+end+'.sql'),'utf8');
 const last='20261111235500_activity_registration_signed',env='crm-d1gkae8ddc930d151';
 try{
  await db.exec(`CREATE ROLE anon;CREATE ROLE authenticated;CREATE ROLE service_role;
   CREATE TABLE public.activities(id bigint primary key,name text,location text,activity_date date,description text,activity_type text,deleted_at timestamptz);
   CREATE TABLE public.persons(id bigint primary key,display_name text,deleted_at timestamptz);
   CREATE TABLE public.crm_access_members(uid text primary key,enabled boolean);
   CREATE TABLE public.crm_browser_devices(uid text,fingerprint text,state text);
   INSERT INTO public.activities(id,name) VALUES(1,'Fixture');
   INSERT INTO public.persons VALUES(2,'Test guest',null);
   INSERT INTO public.crm_access_members VALUES('test-actor',true);INSERT INTO public.crm_browser_devices VALUES('test-actor','test-device','approved');`);
  for(const name of ['20261110110000_activity_registration','20261110160000_activity_registration_shared_token','20261111234500_activity_registration_crypto','20261111235400_activity_registration_write',last])await db.exec(sql(name));
  const keys=Object.fromEntries((await db.query("UPDATE public.activity_registration_signers SET enabled=true RETURNING scope,encode(signing_key,'hex') AS hex")).rows.map(r=>[r.scope,Buffer.from(r.hex,'hex')]));
  await db.exec('SET ROLE anon');
  const staff={actor:'test-actor',fingerprint:'test-device'};
  const body=(scope,action,data={},extra={})=>({action,data,...(scope==='staff'?staff:{}),requestId:crypto.randomUUID(),client:'a'.repeat(64),...extra});
  const invoke=async(scope,payload,keyScope=scope)=>{
   const key=keys[keyScope],proof=makeEnvelope(env,keyScope,key,payload);
   const exec=async()=>{const r=await db.query('SELECT public.crm_registration_'+scope+'_v1($1,$2) AS result',[proof.envelope,proof.mac]);return decryptResult(key,keyScope,proof.nonce,r.rows[0].result);};
   return {result:await exec(),again:exec,proof};
  };
  const call=async(scope,action,data,extra)=>(await invoke(scope,body(scope,action,data,extra))).result;
  assert.equal((await call('staff','listPages',{}, {fingerprint:'unapproved'})).error,'STAFF_ACCESS_DENIED');
  assert.equal((await call('public','listSubmissions',{})).error,'ACCESS_DENIED');
  await assert.rejects(invoke('staff',body('public','getPublishedPage',{slug:'fixture'}),'public'),/ACCESS_DENIED/);
  const saved=await call('staff','savePage',{activityId:'1',slug:'fictional-event',status:'published',content:{title:'Fixture'},formSchema:[]});
  assert.equal(saved.slug,'fictional-event');
  assert.equal((await call('public','getPublishedPage',{slug:saved.slug})).page.activity.name,'Fixture');
  const request=body('public','submit',{slug:saved.slug,attendeeName:'Guest',wechat:'TEST',answers:{}});
  const first=await invoke('public',request);
  await assert.rejects(first.again(),/PROOF_USED/);
  assert.deepEqual((await invoke('public',request)).result,first.result);
  assert.equal((await invoke('public',{...request,data:{...request.data,attendeeName:'Other'}})).result.error,'REQUEST_CONFLICT');
  const hash=v=>crypto.createHash('sha256').update(v).digest('hex');
  const ownerHash=hash(first.result.managementToken),id=first.result.submissionId;
  assert.equal((await call('public','getMyRegistration',{ownerHash})).registrations[0].id,id);
  assert.equal((await call('public','updateMyRegistration',{submissionId:id,ownerHash,attendeeName:'Guest',wechat:'EDIT',answers:{}})).status,'pending');
  assert.equal((await call('staff','listSubmissions',{pageId:saved.page.id})).rows.length,1);
  assert.equal((await call('staff','review',{id,status:'approved'})).row.status,'approved');
  assert.equal((await call('staff','markNotified',{id})).ok,true);
  assert.equal((await call('staff','searchPersons',{keyword:'guest'})).rows[0].id,2);
  assert.equal((await call('staff','linkPerson',{submissionId:id,personId:'2'})).ok,true);
  assert.equal((await call('staff','personActivities',{personId:'2'})).rows[0].id,id);
  assert.equal((await call('staff','activityPeople',{activityId:'1'})).rows[0].personId,'2');
  const rotation=await call('staff','reissueManagementLink',{id});
  assert.equal((await call('public','getMyRegistration',{ownerHash})).error,'REGISTRATION_NOT_FOUND');
  assert.equal((await call('public','getMyRegistration',{ownerHash:hash(rotation.managementToken)})).registrations.length,1);
  await db.exec("RESET ROLE;UPDATE public.activity_registration_signers SET enabled=false WHERE scope='public';SET ROLE anon");
  await assert.rejects(call('public','getPublishedPage',{slug:saved.slug}),/ACCESS_DENIED/);
  assert.equal((await call('staff','listPages',{})).rows.length,1);
  await db.exec("RESET ROLE;UPDATE public.activity_registration_signers SET enabled=(scope='public');SET ROLE anon");
  await assert.rejects(call('staff','listPages',{}),/ACCESS_DENIED/);
  assert.equal((await call('public','getPublishedPage',{slug:saved.slug})).page.slug,saved.slug);
  await db.exec("RESET ROLE;UPDATE public.activity_registration_signers SET enabled=false;UPDATE public.activity_registration_receipts SET expires_at=now()-interval '1 second'");
  await db.exec(sql(last,'.rollback'));
 }finally{await db.close();}
});
