'use strict';
// Run with CRM_PGLITE_MODULE pointing at an isolated PGlite installation.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require(process.env.CRM_PGLITE_MODULE || '@electric-sql/pglite');
(async () => {
 const db = new PGlite();
 try {
  await db.exec(`
   CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
   CREATE TABLE public.persons(id bigint PRIMARY KEY,display_name text,deleted_at timestamptz);
   CREATE TABLE public.customers("Id" integer PRIMARY KEY,person_id bigint REFERENCES public.persons(id),deleted_at timestamptz);
   CREATE TABLE public.activities(id bigint PRIMARY KEY,deleted_at timestamptz);
   CREATE TABLE public.ai_recommendations(id integer PRIMARY KEY,customer_id integer);
   CREATE TABLE public.interactions(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,person_id bigint NOT NULL REFERENCES public.persons(id),
    interaction_type text NOT NULL CHECK(length(btrim(interaction_type)) BETWEEN 1 AND 64),interaction_at timestamptz NOT NULL,channel text CHECK(length(channel)<=100),
    summary text NOT NULL CHECK(length(btrim(summary)) BETWEEN 1 AND 2000),raw_note text CHECK(length(raw_note)<=10000),activity_id bigint REFERENCES public.activities(id),
    source_type text NOT NULL CHECK(source_type IN ('manual','followups','recruit_followups','activity_participants')),source_id bigint,importance smallint DEFAULT 3,
    created_by_uid text,created_at timestamptz NOT NULL DEFAULT now(),CHECK((source_type='manual' AND source_id IS NULL AND NULLIF(btrim(created_by_uid),'') IS NOT NULL) OR (source_type<>'manual' AND source_id IS NOT NULL)));
   CREATE UNIQUE INDEX interactions_source_uidx ON public.interactions(source_type,source_id) WHERE source_id IS NOT NULL;
   CREATE TABLE public.followups("Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,customer_name text NOT NULL,customer_id integer NOT NULL REFERENCES public.customers("Id"),
    followup_notes text,followup_date date,next_followup_date date,next_followup_goal text,created_at timestamptz,updated_at timestamp,deleted_at timestamptz,
    recommendation_id integer,activity_id integer,interaction_summary text,next_action text,next_action_date date,delete_batch_id uuid);
   CREATE VIEW public.followups_view WITH (security_invoker=true) AS SELECT "Id",customer_name FROM public.followups;
   INSERT INTO public.persons VALUES(1,'[CRM_TEST_ONLY] One',NULL),(2,'[CRM_TEST_ONLY] Two',NULL);
   INSERT INTO public.customers VALUES(11,1,NULL),(22,2,NULL);
   INSERT INTO public.activities VALUES(31,NULL);
   INSERT INTO public.ai_recommendations VALUES(41,11),(42,22);
   INSERT INTO public.followups(customer_name,customer_id,followup_date,interaction_summary,followup_notes) VALUES('One',11,'2026-10-01','Historical','Original'),('One',11,NULL,NULL,NULL);
   GRANT USAGE ON SCHEMA public TO service_role; GRANT ALL ON ALL TABLES IN SCHEMA public TO service_role; GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO service_role;
  `);
  const before = (await db.query('SELECT to_jsonb(f) AS row FROM public.followups f ORDER BY "Id"')).rows;
  for (const name of ['20261030220000_unified_interactions','20261030220100_unified_interaction_editor','20261030220200_unified_view_invoker']) {
   await db.exec(fs.readFileSync(path.join(__dirname,'../../cloudbase/migrations',name+'.sql'),'utf8'));
  }
  assert.ok((await db.query("SELECT reloptions FROM pg_class WHERE oid='public.followups_view'::regclass")).rows[0].reloptions.includes('security_invoker=true'));
  const after = (await db.query("SELECT to_jsonb(f)-'interaction_id' AS row FROM public.followups f ORDER BY \"Id\"")).rows;
  assert.deepEqual(after,before,'backfill preserves all original fields');
  assert.equal((await db.query('SELECT count(*)::int AS n FROM public.interactions')).rows[0].n,2);
  assert.deepEqual((await db.query("SELECT interaction_at,time_precision FROM public.interactions WHERE source_id=2")).rows[0],{interaction_at:null,time_precision:'unknown'});
  await db.exec("UPDATE public.followups SET followup_notes='Legacy edit' WHERE \"Id\"=1");
  assert.equal((await db.query('SELECT raw_note FROM public.interactions WHERE source_id=1')).rows[0].raw_note,'Legacy edit');
  await db.exec("UPDATE public.interactions SET summary='Canonical edit',interaction_at='2026-10-02T03:04:00Z' WHERE source_id=1");
  assert.equal((await db.query('SELECT interaction_summary FROM public.followups WHERE "Id"=1')).rows[0].interaction_summary,'Canonical edit');
  await db.exec("UPDATE public.followups SET deleted_at='2026-10-03T00:00:00Z' WHERE \"Id\"=1");
  assert.ok((await db.query('SELECT deleted_at FROM public.interactions WHERE source_id=1')).rows[0].deleted_at);
  await db.exec('UPDATE public.followups SET deleted_at=NULL WHERE "Id"=1');
  assert.equal((await db.query('SELECT deleted_at FROM public.interactions WHERE source_id=1')).rows[0].deleted_at,null);
  await db.exec('SET ROLE service_role');
  const rpc = async (op,data,pid=1) => (await db.query('SELECT public.crm_person_interaction_v1($1,$2,$3,$4::jsonb) AS r',[op,'crm-test-actor',pid,JSON.stringify(data)])).rows[0].r;
  const draft = {requestKey:'ab754b34-8786-4f3a-8378-e972de9bb9af',customer_id:11,interaction_type:'call',interaction_at:'2026-10-30T01:23:45Z',time_precision:'instant',summary:'New event',raw_note:'Full text',channel:'phone',next_followup_date:'2026-11-01',next_followup_goal:'Review',recommendation_id:41,activity_id:31};
  const saved = await rpc('save',draft);
  assert.ok(saved.interaction.id); assert.equal((await rpc('save',draft)).interaction.id,saved.interaction.id,'retry idempotency');
  await assert.rejects(rpc('save',{...draft,summary:'different'}),/REQUEST_CONFLICT/);
  await assert.rejects(rpc('get',{id:saved.interaction.id},2),/NOT_EDITABLE/);
  const snapshot=await rpc('get',{id:saved.interaction.id});
  assert.equal(snapshot.followup.next_followup_goal,'Review');
  await assert.rejects(rpc('save',{...draft,id:saved.interaction.id,version:'wrong'}),/STALE/);
  const update={...draft,id:saved.interaction.id,version:snapshot.version,summary:'Edited'};
  await rpc('save',update);
  const fresh=await rpc('get',{id:saved.interaction.id});
  assert.equal(fresh.followup.interaction_summary,'Edited');
  assert.equal(fresh.interaction.channel,'phone');
  assert.equal(fresh.interaction.interaction_at,'2026-10-30T01:23:45+00:00');
  const unknown=await rpc('get',{id:2});
  await rpc('save',{id:2,version:unknown.version,customer_id:11,interaction_type:'followup',summary:'Verified note',interaction_at:null,time_precision:'unknown'});
  const general=await rpc('save',{...draft,requestKey:'d548b21b-f030-400b-a1f0-7866be706fa3',customer_id:null});
  const generalSnap=await rpc('get',{id:general.interaction.id});
  assert.equal(generalSnap.followup,null);
  await rpc('save',{...draft,id:general.interaction.id,version:generalSnap.version,customer_id:null,summary:'Manual edited'});
  await rpc('remove',{id:saved.interaction.id,version:fresh.version});
  assert.ok((await db.query('SELECT deleted_at FROM public.interactions WHERE id=$1',[saved.interaction.id])).rows[0].deleted_at);
  await db.exec('RESET ROLE; SET ROLE anon');
  await assert.rejects(rpc('get',{id:2}),/permission denied/);
  await db.exec('RESET ROLE');
  for(const name of ['20261030220100_unified_interaction_editor','20261030220000_unified_interactions']) await db.exec(fs.readFileSync(path.join(__dirname,'../../cloudbase/migrations',name+'.rollback.sql'),'utf8'));
  assert.equal((await db.query('SELECT count(*)::int AS n FROM public.interactions')).rows[0].n,4,'rollback keeps history');
  console.log('PASS: migration preservation, missing dates, both write directions, soft delete/restore, hard delete, scope, idempotency, optimistic edits, source fields, anon denial and safe rollback');
 } finally { await db.close(); }
})().catch(error=>{console.error(error.message);process.exitCode=1;});
